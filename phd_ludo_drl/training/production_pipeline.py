@dataclass
class RunArtifactPaths:
    """Explicit filesystem paths for all artifacts generated by an experiment run."""
    root: Path
    checkpoints: Path
    logs: Path
    results: Path
    config_snapshot: Path
    metadata: Path
    checkpoint_manifest: Path
    metrics_jsonl: Path
    metrics_csv: Path
    training_log: Path
    summary: Path
    failure_recovery: Path

    @classmethod
    def create(cls, base_dir: Path, run_type: RunType, exp_id: str) -> "RunArtifactPaths":
        sub_dir = RUN_TYPE_SUBDIRS[run_type]
        run_root = base_dir / "experiments" / sub_dir / exp_id
        checkpoints_dir = run_root / "checkpoints"
        logs_dir = run_root / "logs"
        results_dir = run_root / "results"

        for d in [checkpoints_dir, logs_dir, results_dir]:
            d.mkdir(parents=True, exist_ok=True)

        return cls(
            root=run_root,
            checkpoints=checkpoints_dir,
            logs=logs_dir,
            results=results_dir,
            config_snapshot=run_root / "config_frozen.yaml",
            metadata=run_root / "metadata.json",
            checkpoint_manifest=checkpoints_dir / "checkpoint_manifest.json",
            metrics_jsonl=logs_dir / "metrics.jsonl",
            metrics_csv=logs_dir / "metrics.csv",
            training_log=logs_dir / "training.log",
            summary=results_dir / "summary.json",
            failure_recovery=run_root / "failure_recovery.json",
        )


def compute_file_sha256(filepath: Path) -> str:
    """Compute SHA-256 hash of a file for integrity verification."""
    hasher = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest()


class ProductionTrainingPipeline:
    """Industrial-grade, scientifically rigorous training pipeline for PhD Ludo DRL."""

    def __init__(self, base_dir: Optional[Path] = None):
        self.base_dir = (base_dir or Path.cwd()).resolve()

    def generate_experiment_id(
        self,
        algorithm: str,
        seed: int,
        run_type: RunType,
        encoding: str = "structured_cnn",
        custom_tag: Optional[str] = None,
    ) -> str:
        """Create a standardized, collision-resistant experiment identifier."""
        algo = normalize_algorithm_name(algorithm).upper()
        prefix = RUN_TYPE_PREFIXES[run_type]
        now_str = datetime.now().strftime("%Y%m%d_%H%M%S")
        tag_str = f"_{custom_tag}" if custom_tag else ""
        return f"{prefix}{algo}_{encoding}_{seed}_{now_str}{tag_str}"

    def run_experiment(
        self,
        algorithm: str,
        seed: int = 42,
        total_steps: int = 500_000,
        run_type: Union[RunType, str] = RunType.FINAL_EXPERIMENT,
        opponent_type: str = "random",
        eval_interval: Optional[int] = None,
        eval_games: int = 100,
        checkpoint_interval: int = DEFAULT_CHECKPOINT_INTERVAL,
        config: Optional[ProjectConfig] = None,
        description: str = "",
        device: Optional[torch.device] = None,
        resume: bool = False,
        resume_from_dir: Optional[Path] = None,
    ) -> Dict[str, Any]:
        """Execute an independent, deterministic training run adhering to protocol governance.

        Args:
            algorithm: Algorithm identifier ('dqn', 'ppo', 'model3', 'model4').
            seed: Master random seed (42, 101, 202, 303, 404).
            total_steps: Total interaction steps to train.
            run_type: RunType enum or str ('smoke_test', 'pilot_run', 'final_experiment').
            opponent_type: Benchmark opponent ('random' or 'expert').
            eval_interval: Interval between periodic evaluation tournaments.
            eval_games: Number of evaluation games per tournament.
            checkpoint_interval: Step frequency for intermediate checkpoints.
            config: Optional ProjectConfig override.
            description: Description of the experiment.
            device: Torch computation device.
            resume: Whether to attempt failure recovery and resume from existing checkpoint.
            resume_from_dir: Specific run directory to resume from if resume=True.

        Returns:
            Dictionary containing run metadata, training metrics, eval outcomes, and artifact paths.
        """
        algo = normalize_algorithm_name(algorithm)
        rtype = normalize_run_type(run_type)
        cfg = config or ConfigManager.load_config()
        is_final = (rtype == RunType.FINAL_EXPERIMENT)

        if resume_from_dir is not None:
            exp_id = resume_from_dir.name
            paths = RunArtifactPaths(
                root=resume_from_dir,
                checkpoints=resume_from_dir / "checkpoints",
                logs=resume_from_dir / "logs",
                results=resume_from_dir / "results",
                config_snapshot=resume_from_dir / "config_frozen.yaml",
                metadata=resume_from_dir / "metadata.json",
                checkpoint_manifest=resume_from_dir / "checkpoints" / "checkpoint_manifest.json",
                metrics_jsonl=resume_from_dir / "logs" / "metrics.jsonl",
                metrics_csv=resume_from_dir / "logs" / "metrics.csv",
                training_log=resume_from_dir / "logs" / "training.log",
                summary=resume_from_dir / "results" / "summary.json",
                failure_recovery=resume_from_dir / "failure_recovery.json",
            )
        else:
            exp_id = self.generate_experiment_id(algo, seed, rtype, encoding=cfg.encoding.type)
            paths = RunArtifactPaths.create(self.base_dir, rtype, exp_id)

        # STRICT GOVERNANCE CHECK: Smoke test must NEVER be labelled as a final experiment
        validate_run_classification(
            run_type=rtype,
            experiment_id=exp_id,
            total_steps=total_steps,
            is_final_experiment=is_final,
            description=description,
        )

        # Step 2: Protection against overwriting existing raw runs
        if not resume and paths.summary.exists():
            raise FileExistsError(
                f"PROTECTION VIOLATION: Experiment summary already exists at '{paths.summary}'. "
                "Raw runs cannot be overwritten! Specify resume=True or use a fresh run ID."
            )

        # Step 3: Logger Initialization
        logger = setup_logger(
            name=exp_id,
            log_dir=paths.logs,
            log_to_console=True,
            filename="training.log",
        )
        logger.info("=" * 80)
        logger.info(f"STARTING {rtype.value.upper()}: {exp_id}")
        logger.info(f"Algorithm: {algo.upper()} | Master Seed: {seed} | Steps: {total_steps:,}")
        logger.info(f"Protocol: {FROZEN_PROTOCOL_VERSION} | Opponent: {opponent_type}")
        logger.info(f"Run Directory: {paths.root}")
        logger.info("=" * 80)

        # Step 4: Capture Git Provenance & Environment State
        provenance: VersionProvenance = capture_version_provenance(self.base_dir)
        logger.info(f"Git Commit: {provenance.git_commit_short} (branch: {provenance.git_branch}, dirty: {provenance.git_dirty})")
        logger.info(f"Environment: Python {provenance.python_version}, PyTorch {provenance.torch_version}, Platform: {provenance.platform_system}")

        # Step 5: Save Frozen Configuration Snapshot & Run Metadata
        ConfigManager.save_config(cfg, paths.config_snapshot)
        logger.info(f"Saved frozen configuration snapshot to {paths.config_snapshot}")

        config_hash = ExperimentIdentifier.generate_hash(cfg.to_dict())
        metadata_payload = {
            "experiment_id": exp_id,
            "run_type": rtype.value,
            "is_final_experiment": is_final,
            "protocol_version": FROZEN_PROTOCOL_VERSION,
            "algorithm": algo,
            "seed": seed,
            "derived_seeds": {
                "environment_seed": seed,
                "agent_seed": seed,
                "opponent_seed": seed + 10,
                "evaluation_seed": seed + 1000,
            },
            "encoding": cfg.encoding.type,
            "total_steps": total_steps,
            "opponent_type": opponent_type,
            "eval_games": eval_games,
            "eval_interval": eval_interval,
            "checkpoint_interval": checkpoint_interval,
            "config_hash": config_hash,
            "description": description or f"{rtype.value} for {algo.upper()} seed {seed}",
            "created_at_utc": datetime.now(timezone.utc).isoformat(),
            "provenance": provenance.to_dict(),
        }
        with open(paths.metadata, "w", encoding="utf-8") as f:
            json.dump(metadata_payload, f, indent=2)

        # Step 6: Deterministic Seeding (Protocol Section 12)
        set_seed(seed)
        logger.info(f"Deterministic seed {seed} registered across Python, NumPy, PyTorch CPU/CUDA.")

        # Step 7: Environment & Agent Initialization
        env = LudoEnvironment(seed=seed, auto_advance_no_moves=True)
        agent = create_agent(algorithm=algo, config=cfg, device=device)
        opponent = create_opponent(opponent_type=opponent_type, seed=seed + 10)

        # Step 8: Failure Recovery Check & Resumption
        initial_step = 0
        manifest_entries: List[Dict[str, Any]] = []

        if paths.checkpoint_manifest.exists():
            try:
                manifest_data = json.loads(paths.checkpoint_manifest.read_text(encoding="utf-8"))
                manifest_entries = manifest_data.get("checkpoints", [])
            except Exception as e:
                logger.warning(f"Could not parse existing manifest: {e}")

        if resume:
            latest_ckpt, resume_step = self._discover_latest_checkpoint(paths.checkpoints, manifest_entries)
            if latest_ckpt is not None and latest_ckpt.exists():
                logger.info(f"FAILURE RECOVERY: Resuming from checkpoint '{latest_ckpt}' at step {resume_step:,}...")
                agent.load_checkpoint(latest_ckpt)
                initial_step = resume_step
                logger.info(f"Successfully restored agent state from step {initial_step:,}.")
            else:
                logger.info("Resume requested, but no existing checkpoints found. Starting from step 0.")

        # Step 9: Trainer Initialization
        trainer = create_trainer(
            algorithm=algo,
            agent=agent,
            opponent=opponent,
            env=env,
            config=cfg,
        )

        # Step 10: Setup Metrics Streamers
        metrics_csv_exists = paths.metrics_csv.exists()
        csv_file = open(paths.metrics_csv, "a", newline="", encoding="utf-8")
        csv_writer = csv.writer(csv_file)
        if not metrics_csv_exists:
            csv_writer.writerow(["timestamp_utc", "step", "episode", "reward", "loss", "win_rate"])
            csv_file.flush()

        jsonl_file = open(paths.metrics_jsonl, "a", encoding="utf-8")

        def log_step_metrics(step_data: Dict[str, Any]) -> None:
            """Append real-time training step metrics to disk without fake data."""
            ts = datetime.now(timezone.utc).isoformat()
            s = step_data.get("step", initial_step)
            ep = step_data.get("episode", 0)
            rew = step_data.get("episode_reward", 0.0)
            loss_val = step_data.get("loss", None)

            record = {
                "timestamp_utc": ts,
                "step": s,
                "episode": ep,
                "loss": loss_val,
                "mean_q": step_data.get("mean_q"),
                "epsilon": step_data.get("epsilon"),
                "policy_loss": step_data.get("policy_loss"),
                "value_loss": step_data.get("value_loss"),
                "entropy": step_data.get("entropy"),
                "critic_loss": step_data.get("critic_loss"),
                "actor_loss": step_data.get("actor_loss"),
                "alpha": step_data.get("alpha"),
            }
            jsonl_file.write(json.dumps(record) + "\n")
            jsonl_file.flush()

            csv_writer.writerow([ts, s, ep, f"{rew:.4f}", f"{loss_val:.6f}" if loss_val is not None else "", ""])
            csv_file.flush()

        def on_checkpoint_saved(step_num: int, ckpt_path: Path) -> None:
            """Track checkpoint in the manifest with SHA-256 integrity hash."""
            try:
                sha = compute_file_sha256(ckpt_path)
                size = ckpt_path.stat().st_size
                manifest_entries.append({
                    "step": step_num,
                    "filename": ckpt_path.name,
                    "path": str(ckpt_path.relative_to(paths.root)),
                    "size_bytes": size,
                    "sha256": sha,
                    "timestamp_utc": datetime.now(timezone.utc).isoformat(),
                })
                manifest_doc = {
                    "experiment_id": exp_id,
                    "algorithm": algo,
                    "seed": seed,
                    "protocol_version": FROZEN_PROTOCOL_VERSION,
                    "checkpoints": manifest_entries,
                    "latest_checkpoint": str(ckpt_path.relative_to(paths.root)),
                }
                with open(paths.checkpoint_manifest, "w", encoding="utf-8") as mf:
                    json.dump(manifest_doc, mf, indent=2)
                logger.info(f"Checkpoint saved: {ckpt_path.name} (step {step_num:,}, sha256={sha[:8]}...)")
            except Exception as exc:
                logger.error(f"Error updating checkpoint manifest: {exc}")

        # Step 11: Execute Training Loop with Failure Recovery Tracking
        start_time = time.time()
        logger.info(f"Executing training loop from step {initial_step:,} to {total_steps:,}...")

        try:
            training_metrics = trainer.train(
                total_steps=total_steps,
                eval_interval=eval_interval,
                eval_games=eval_games,
                checkpoint_dir=paths.checkpoints,
                callback=log_step_metrics,
                initial_step=initial_step,
                checkpoint_interval=checkpoint_interval,
                checkpoint_callback=on_checkpoint_saved,
            )
        except Exception as err:
            elapsed_fail = round(time.time() - start_time, 2)
            logger.error(f"TRAINING CRASHED after {elapsed_fail:.1f}s: {err}")
            # Record failure state for recovery
            failure_doc = {
                "experiment_id": exp_id,
                "algorithm": algo,
                "seed": seed,
                "run_type": rtype.value,
                "interrupted_at_utc": datetime.now(timezone.utc).isoformat(),
                "runtime_seconds": elapsed_fail,
                "error": str(err),
                "traceback": traceback.format_exc(),
                "resumable": True,
            }
            with open(paths.failure_recovery, "w", encoding="utf-8") as ff:
                json.dump(failure_doc, ff, indent=2)
            csv_file.close()
            jsonl_file.close()
            raise err

        csv_file.close()
        jsonl_file.close()

        # Step 12: Save Final Checkpoint
        final_ckpt_path = paths.checkpoints / "final_model.pt"
        agent.save_checkpoint(final_ckpt_path)
        on_checkpoint_saved(total_steps, final_ckpt_path)
        logger.info(f"Saved definitive final checkpoint to {final_ckpt_path}")

        # Step 13: Post-Training Evaluation Tournament
        logger.info(f"Running tournament evaluation ({eval_games} games vs {opponent_type})...")
        eval_summary = trainer.evaluate(num_games=eval_games)
        logger.info(
            f"Eval Outcome: Win Rate = {eval_summary.p0_win_rate:.2%} | "
            f"Avg Turns = {eval_summary.avg_turns:.1f} | Avg Reward = {eval_summary.avg_p0_reward:.2f}"
        )

        runtime_seconds = round(time.time() - start_time, 2)

        # Step 14: Compile and Save Complete Results Artifact
        result_payload = {
            "metadata": metadata_payload,
            "runtime_seconds": runtime_seconds,
            "training_metrics": training_metrics.to_dict(),
            "evaluation_metrics": eval_summary.to_dict(),
            "artifacts": {
                "root_dir": str(paths.root.relative_to(self.base_dir)),
                "checkpoint": str(final_ckpt_path.relative_to(self.base_dir)),
                "checkpoint_manifest": str(paths.checkpoint_manifest.relative_to(self.base_dir)),
                "log_dir": str(paths.logs.relative_to(self.base_dir)),
                "metrics_jsonl": str(paths.metrics_jsonl.relative_to(self.base_dir)),
                "metrics_csv": str(paths.metrics_csv.relative_to(self.base_dir)),
                "results_dir": str(paths.results.relative_to(self.base_dir)),
                "summary": str(paths.summary.relative_to(self.base_dir)),
            },
        }

        with open(paths.summary, "w", encoding="utf-8") as sf:
            json.dump(result_payload, sf, indent=2)

        # If a failure recovery file existed, clean it up or mark resolved
        if paths.failure_recovery.exists():
            try:
                paths.failure_recovery.unlink()
            except Exception:
                pass

        logger.info("=" * 80)
        logger.info(f"COMPLETED {rtype.value.upper()}: {exp_id} in {runtime_seconds:.1f}s")
        logger.info(f"Summary written to {paths.summary}")
        logger.info("=" * 80)

        return result_payload

    def _discover_latest_checkpoint(
        self,
        checkpoints_dir: Path,
        manifest_entries: List[Dict[str, Any]],
    ) -> Tuple[Optional[Path], int]:
        """Find the latest valid checkpoint and corresponding step count."""
        if manifest_entries:
            # Sort by step descending
            valid_entries = sorted(manifest_entries, key=lambda x: x.get("step", 0), reverse=True)
            for entry in valid_entries:
                p = checkpoints_dir / entry["filename"]
                if p.exists():
                    return p, entry.get("step", 0)

        # Fallback: scan checkpoints directory
        candidates = list(checkpoints_dir.glob("*_step_*.pt"))
        if candidates:
            def extract_step(path: Path) -> int:
                try:
                    parts = path.stem.split("_")
                    return int(parts[-1])
                except Exception:
                    return 0
            candidates.sort(key=extract_step, reverse=True)
            best = candidates[0]
            return best, extract_step(best)

        final_pt = checkpoints_dir / "final_model.pt"
        if final_pt.exists():
            return final_pt, 0

        return None, 0

    def is_run_completed(
        self,
        algorithm: str,
        seed: int,
        run_type: RunType = RunType.FINAL_EXPERIMENT,
        target_steps: int = FINAL_EXPERIMENT_STEPS,
    ) -> Tuple[bool, Optional[Path], Optional[Dict[str, Any]]]:
        """Check if a run with the given algorithm and seed is already completed."""
        algo = normalize_algorithm_name(algorithm)
        sub_dir = RUN_TYPE_SUBDIRS[run_type]
        search_dir = self.base_dir / "experiments" / sub_dir
        if not search_dir.exists():
            return False, None, None

        prefix = RUN_TYPE_PREFIXES[run_type]
        pattern = f"{prefix}{algo.upper()}_*_{seed}_*"
        matching_dirs = sorted(search_dir.glob(pattern), reverse=True)

        for rdir in matching_dirs:
            summary_path = rdir / "results" / "summary.json"
            if summary_path.exists():
                try:
                    data = json.loads(summary_path.read_text(encoding="utf-8"))
                    actual_steps = data.get("training_metrics", {}).get("total_steps", 0)
                    if actual_steps >= target_steps:
                        return True, rdir, data
                except Exception:
                    pass

        return False, None, None

    def run_campaign(
        self,
        algorithms: Optional[List[str]] = None,
        seeds: Optional[List[int]] = None,
        total_steps: int = FINAL_EXPERIMENT_STEPS,
        eval_interval: int = DEFAULT_EVAL_INTERVAL,
        eval_games: int = DEFAULT_EVAL_GAMES,
        checkpoint_interval: int = DEFAULT_CHECKPOINT_INTERVAL,
        resume: bool = True,
    ) -> Dict[str, Any]:
        """Orchestrate the definitive 20-run final training campaign.

        - 4 models: DQN, PPO, Discrete SAC, C51
        - 5 master seeds: [42, 101, 202, 303, 404]
        - 500,000 steps per run
        - Independent run directories in experiments/final_experiments/
        - Automatically skips and preserves already completed runs
        """
        algos = [normalize_algorithm_name(a) for a in (algorithms or SUPPORTED_ALGORITHMS)]
        s_list = seeds or MASTER_SEEDS
        total_planned_runs = len(algos) * len(s_list)

        campaign_dir = self.base_dir / "experiments" / "final_experiments"
        campaign_dir.mkdir(parents=True, exist_ok=True)
        status_file = campaign_dir / "campaign_status.json"

        campaign_start = time.time()
        campaign_start_utc = datetime.now(timezone.utc).isoformat()

        print("=" * 80)
        print("PHASE 9 — PRODUCTION TRAINING CAMPAIGN")
        print(f"Protocol: {FROZEN_PROTOCOL_VERSION}")
        print(f"Algorithms: {[a.upper() for a in algos]}")
        print(f"Master Seeds: {s_list}")
        print(f"Total Budget per Run: {total_steps:,} steps")
        print(f"Total Planned Runs: {total_planned_runs}")
        print("=" * 80)

        completed_runs: List[Dict[str, Any]] = []
        skipped_runs: List[Dict[str, Any]] = []
        failed_runs: List[Dict[str, Any]] = []

        run_num = 0
        for algo in algos:
            for seed in s_list:
                run_num += 1
                header = f"[{run_num}/{total_planned_runs}] {algo.upper()} (Seed {seed})"
                print(f"\nEvaluating run {header}...")

                # Check if already completed
                is_done, done_dir, done_data = self.is_run_completed(
                    algorithm=algo,
                    seed=seed,
                    run_type=RunType.FINAL_EXPERIMENT,
                    target_steps=total_steps,
                )

                if is_done and done_data is not None and done_dir is not None:
                    print(f"  --> SKIPPED: Already completed in '{done_dir.name}' ({total_steps:,} steps). Preserving raw run.")
                    skipped_runs.append({
                        "algorithm": algo,
                        "seed": seed,
                        "experiment_id": done_dir.name,
                        "status": "skipped_already_completed",
                        "total_steps": done_data["training_metrics"]["total_steps"],
                        "summary_path": str((done_dir / "results" / "summary.json").relative_to(self.base_dir)),
                    })
                    continue

                print(f"  --> STARTING EXECUTION: {header}")
                try:
                    res = self.run_experiment(
                        algorithm=algo,
                        seed=seed,
                        total_steps=total_steps,
                        run_type=RunType.FINAL_EXPERIMENT,
                        opponent_type="random",
                        eval_interval=eval_interval,
                        eval_games=eval_games,
                        checkpoint_interval=checkpoint_interval,
                        description=f"Phase 9 Final Benchmark: {algo.upper()} Seed {seed}",
                        resume=resume,
                    )
                    completed_runs.append({
                        "algorithm": algo,
                        "seed": seed,
                        "experiment_id": res["metadata"]["experiment_id"],
                        "status": "completed",
                        "total_steps": res["training_metrics"]["total_steps"],
                        "win_rate": res["evaluation_metrics"]["p0_win_rate"],
                        "runtime_seconds": res["runtime_seconds"],
                    })
                except Exception as ex:
                    print(f"  --> FAILED: {header} failed with error: {ex}")
                    failed_runs.append({
                        "algorithm": algo,
                        "seed": seed,
                        "status": "failed",
                        "error": str(ex),
                    })

                # Save intermediate status
                interim_status = {
                    "campaign": "PhD Ludo DRL Production Campaign",
                    "protocol_version": FROZEN_PROTOCOL_VERSION,
                    "campaign_start_utc": campaign_start_utc,
                    "latest_update_utc": datetime.now(timezone.utc).isoformat(),
                    "total_planned": total_planned_runs,
                    "completed_count": len(completed_runs),
                    "skipped_count": len(skipped_runs),
                    "failed_count": len(failed_runs),
                    "completed_runs": completed_runs,
                    "skipped_runs": skipped_runs,
                    "failed_runs": failed_runs,
                }
                with open(status_file, "w", encoding="utf-8") as sf:
                    json.dump(interim_status, sf, indent=2)

        total_elapsed = round(time.time() - campaign_start, 2)
        final_status = {
            "campaign": "PhD Ludo DRL Production Campaign",
            "protocol_version": FROZEN_PROTOCOL_VERSION,
            "campaign_start_utc": campaign_start_utc,
            "campaign_end_utc": datetime.now(timezone.utc).isoformat(),
            "total_runtime_seconds": total_elapsed,
            "total_planned": total_planned_runs,
            "completed_this_session": len(completed_runs),
            "skipped_already_done": len(skipped_runs),
            "failed_this_session": len(failed_runs),
            "status": "SUCCESS" if len(failed_runs) == 0 else "PARTIAL_FAILURE",
            "completed_runs": completed_runs,
            "skipped_runs": skipped_runs,
            "failed_runs": failed_runs,
        }
        with open(status_file, "w", encoding="utf-8") as sf:
            json.dump(final_status, sf, indent=2)

        print("\n" + "=" * 80)
        print("CAMPAIGN COMPLETED")
        print(f"Status: {final_status['status']}")
        print(f"Completed this session: {len(completed_runs)} | Skipped: {len(skipped_runs)} | Failed: {len(failed_runs)}")
        print(f"Campaign status saved to: {status_file}")
        print("=" * 80)

        return final_status

    def run_smoke_test(
        self,
        algorithms: Optional[List[str]] = None,
        steps: int = 100,
        seed: int = 42,
        checkpoint_interval: int = 50,
        eval_games: int = 2,
    ) -> Dict[str, Any]:
        """Execute a rapid, non-destructive smoke test across specified models.

        Validates:
        - Deterministic seed registry
        - Independent run directory creation under experiments/smoke_tests/
        - Configuration snapshotting
        - Real checkpoint generation
        - Streaming metrics logging
        - Failure recovery / resumption
        - Invariant: NEVER labelled as final experiment
        """
        algos = [normalize_algorithm_name(a) for a in (algorithms or SUPPORTED_ALGORITHMS)]
        results = {}

        print("=" * 80)
        print(f"RUNNING SMOKE TEST VALIDATION ({steps} steps/model, seed={seed})")
        print("INVARIANT: Run type is strictly SMOKE_TEST and NEVER final experiment")
        print("=" * 80)

        for algo in algos:
            res = self.run_experiment(
                algorithm=algo,
                seed=seed,
                total_steps=steps,
                run_type=RunType.SMOKE_TEST,
                opponent_type="random",
                eval_interval=None,
                eval_games=eval_games,
                checkpoint_interval=checkpoint_interval,
                description=f"Automated pipeline smoke test for {algo.upper()}",
            )
            # Assert smoke test invariant
            assert res["metadata"]["run_type"] == "smoke_test"
            assert res["metadata"]["is_final_experiment"] is False
            assert "EXP_FINAL" not in res["metadata"]["experiment_id"]
            results[algo] = res

        print("=" * 80)
        print(f"ALL SMOKE TESTS PASSED: {list(results.keys())}")
        print("=" * 80)
        return results
